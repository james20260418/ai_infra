// JPOV SsrRenderer —— 屏幕空间反射 v2（体素桩模型 + 区间重叠判据）
//
// 设计：docs/jpov_ssr_v2_design.md。本文件的每条结论都能在那份文档里找到出处，
//       括号里的 §x.y 就是章节号 —— 改接口之前先读那一节，别重新论证一遍。
//
// ★ 本文件当前是**接口定义**（只有声明，没有实现）：给需求者 review 用。
//   实现（GLSL / FBO / 分段并行的 DDA）按 §16 的顺序另开 commit。
//
// ───────────────────────────────────────────────────────────────────────────
// 定位
// ───────────────────────────────────────────────────────────────────────────
// 一个**全屏后处理子渲染器**，与 SmaaRenderer / HorizonFogRenderer 平级。
//
//   in : 本帧已经画完的**不透明** HDR 颜色 + 场景深度 + 反射体法线 + 相机 + 一个厚度系数
//   out: 每像素一条「镜面方向上看到的颜色」+ 一个二值覆盖率 A ∈ {0,1}
//
// 它**不知道材质、不读环境探针、不做平滑、不写 HDR**——那些全都属于 composite（§7/§8）。
// 这条边界是刻意的：模块只报事实（命中 / 拿不到），处置权归消费端。
//
// ───────────────────────────────────────────────────────────────────────────
// 一句话算法
// ───────────────────────────────────────────────────────────────────────────
// 把屏幕深度图读成「每个像素一根从前表面 z 朝远处挤出厚度 T 的实心方柱」（§4.1）；
// 对每个像素沿镜面方向、在**屏幕格子**上做 2D DDA，逐格只问一个问题：
//
//     射线在这一格里的「视深区间」 与 这一格柱子的 [z, z+T] 有重叠吗？
//
// 有 ⇒ 命中，取那一格的颜色（最近邻，不插值）；没有 ⇒ 前进一格。
// 三行判据、**不解任何方程**（§5.1）。
//
// ── 命中面朝向判据（2026-10-30 第一档，Danis：「正面当背面用无论如何不能不穿帮」）──
// 第四行：**射线必须扎进命中面**（R·N < 0）。R·N ≥ 0 ⇒ 射线是从这个面的背面/内部
// 穿出来的 ⇒ 不算命中，继续 march。
//
// 为什么必不可少（不是调观感）：深度缓冲里只有「相机看得见的那一面」的颜色和法线。
// 镜子往上看桌子底面 / 柱体背面时，那些面在屏幕空间里**没有像素**，旧判据会把桌子
// 顶面的颜色（包括它刺眼的高光）填到倒影里 ⇒ “桌子底下也在发光”。
// 拒掉以后 A = 0 ⇒ composite 回落到环境探针（**不是黑**），这才是可接受的错。
//
// 依赖：normal_tex 的 **.z ≥ 0.5 = 这一格有法线数据**（接入层的降采样必须把它带下去）。
// 没有法线数据时判据不生效、维持旧行为。
//
// 已知边界（下一档要补的）：属性 pass 目前只覆盖 object3d（静态实例 / 蒙皮 / 图元
// 各自还需要一份 attr VS），所以这些物体上的背面命中依旧按旧规则走。真实厚度
// （背面深度 pass）也还没有 ⇒ “深到柱子内部”仍靠统一 T 兜着。
//
// ── 并行化（2026-10-29 Danis 定，**替代** §5.5 的 min 金字塔）──
// 把这条射线按**屏幕弧长**切成 T² 段等长段（每段 L = max_ray_pixels / T² px），
// 一段一个 lane 同时跑：第 k 段的 lane 从 σ = k·L 起自己走 DDA，报「本段最早的命中」——
// 记成**命中格内的中点** s_mid = ½(s_enter + s_exit)。T² 个 lane 的结果取 min，就是整条
// 射线的碰撞位置。中点保证从 s 反推的 uv **一定落在那个命中格内**，而柱内颜色处处相同
// ⇒ s 的截断误差不影响取色（这也是"取 min 能成立"的真正前提）。
//   · 格子是**原子单位**（1 px），所以每段不要短于约 4 px，否则相邻 lane 重复判同一格
//     （冗余 ≈ 1 + 1/L）。不是"并行不了"，是"切不出半个格子"。
//   · 每段步数上限取对角线最坏情况 ceil(1.414·L)+3 ⇒ 每段都走得完、绝不半路截断，
//     覆盖 = T²·L = max_ray_pixels（精确），每像素判据次数 ≤ 1.414·max_ray_pixels + T²
//     （**与场景几何无关**，全屏一致）。
//   · 没有层级、没有分支树、没有每帧建的金字塔 ⇒ 帧成本可解析，gold 不会被性能调优带崩。
//
// ───────────────────────────────────────────────────────────────────────────
// 契约（实现时逐条照抄，§2.1）
// ───────────────────────────────────────────────────────────────────────────
//  1. 分辨率 1:1：输入什么分辨率，输出什么分辨率；内部不降采样、不升采样。
//     分辨率是**调用方**的成本旋钮，模块不感知。（v1 失败的直接原因就是模块内降采样。）
//  2. rgb 是**纯辐亮度**：不乘 Fresnel、不乘 (F0·A+B)、不乘 AO。调用方乘一次、只乘一次。
//  3. a == 0 时 rgb **无意义**（写 0 只为避免未初始化内存）。**禁止**用 rgb == 0 判断状态。
//  4. 模块**不读环境探针**：a == 0 的兜底与一切柔和过渡都归 composite，
//     否则「环境镜面项」会出现第二份实现（改一处、另一处不动的那种 bug）。
//  5. **决定论**：同输入同输出，逐字节。无历史、无抖动、无时序、无随机、无上采样。
//  6. **不改输入、不读自身输出**：同一 pass 内读写同一张颜色纹理 = 反馈环。
//  7. **成本可解析界定**：≤ 1.414·max_ray_pixels + T² 次格子判据 + T² 次归约取样，
//     与场景几何无关。tile_size 只改**并发粒度**：radiance 逐字节相同；调试用的 hit_s
//     是"命中格内的中点"，段边界一变中点会挪（但一定还在同一格里）。
//
// ───────────────────────────────────────────────────────────────────────────
// 管线位置（§14，三条硬约束违反任何一条都会出难查的 bug）
// ───────────────────────────────────────────────────────────────────────────
//   ① 不透明 3D pass → HDR 颜色(RGBA16F) + MRT#1 场景深度(R32F) + 属性 pass 写法线
//   ② 本模块：in = ① 的三张图 → out = radiance.rgb + A
//   ③ composite（全分辨率，**唯一知道材质的地方**）：
//          L = mix(EnvSpecularTerm(...), ssr.rgb, A_soft)
//          color += (F0·AB.x + AB.y) · ao · L
//   ④ strip → 粒子/体积火 → 雾 → Bloom → tonemap
//
//   · ① 的颜色必须是**未加雾**的：雾在 ④ 加，倒影才会跟着反射体一起被雾化。
//   · ① 的颜色必须是**半透明之前**的：strip 不写场景深度、颜色会污染反射源。
//   · ③ 必须读颜色**副本**（或金字塔），不能读正在写的 HDR。
//
// ───────────────────────────────────────────────────────────────────────────
// 数值骨架：三个量对屏幕参数 σ 的依赖（§3，最容易搞错的地方）
// ───────────────────────────────────────────────────────────────────────────
//   σ = 沿屏幕直线的像素弧长（起点 σ=0）。
//     · 屏幕位置 (x,y) 对 σ **线性**（射影把 3D 直线映成直线）
//     · 视距 d = −z_view 对 σ **双曲线**（"z 看起来不线性"就来自这里）
//     · 深度倒数 w = 1/d 对 σ **线性**（射影几何的恒等式，也是硬件透视正确插值的同一件事）
//   ⇒ 格子内的深度区间端点用 mix(w_in, w_out, t) 求是**精确**的；
//     **绝不能用 mix(d_in, d_out, t)**：掠射时（d 从 1 m 到 1000 m）中点线性插值给 500 m，
//     真值 2 m，误差两个数量级。
//
// 唯一破例：射线朝相机走（R.z > 0）会穿过 d = 0 的极点，那里投影翻到另一支，线性失效。
// 处理 = 把射线长度裁到近平面之前（§3.2）：
//     rayLen = min(max_distance_m, far_plane, (−near_plane − P.z) / R.z)
// 裁剪只缩短 σ 的取值范围，不破坏线性性。
//
// ───────────────────────────────────────────────────────────────────────────
// 厚度模型（§9，整套算法唯一允许的假设，只有一个参数）
// ───────────────────────────────────────────────────────────────────────────
//     T = max(c · d_hit, min_thickness_m),  c = thickness_pixels · θ_px
//     θ_px = 垂直 FOV(弧度) / 屏幕高(像素)
//
//   · d_hit 用的是**命中那一格自己的**深度，不是反射体像素的、也不是格子平均值
//     （轮廓格内 d_surf 可以差 50 倍，用错端点 T 就跟着错 50 倍）。
//   · 桩模型下 T 是**纯几何量**（判据是区间重叠，与每格穿透量无关）⇒ c 只影响
//     「允许多少拉黏」这一件观感的事，不影响会不会漏。这是放弃双线性深度面的真正理由（§4.2）。
//   · 按 θ_px 折算 ⇒ 换分辨率/换 FOV 观感一致。**不要**写死绝对系数。
//
// ───────────────────────────────────────────────────────────────────────────
// A 的语义：**覆盖率**，不是**正确率**（§6，最容易被误解的一节）
// ───────────────────────────────────────────────────────────────────────────
//   射线出屏 / 屏幕外几何 → A = 0（**显式**：没数据）
//   厚度 T 不对、薄于单像素穿透量 → A = 1（**静默**：给了答案，可能不准）
//   ⇒ A 用来做统计（"倒影里有多少是真算出来的"）有效；用来担保正确性无效。
//
// ───────────────────────────────────────────────────────────────────────────
// 已知边界（§13，如实记录，别当 bug 修）
// ───────────────────────────────────────────────────────────────────────────
//   · 轮廓外侧一圈探针色：射线穿过轮廓后，它该看的东西根本不在屏幕上（§10② 才能解）。
//   · 薄物体倒影恒定加粗 ≈ thickness_pixels 像素（T ∝ d 偏大的代价，可调不可消除）。
//   · 稀疏几何（树冠、栅栏）倒影成实心（T 远大于叶片真实厚度）。
//   · 掠射时倒影锯齿/闪烁（几公里水面压进几像素，采样不足，属分辨率固有）。
//
// ★ 接口定义期发现的**待确认**一处（设计文档 §5.3 只写了"起点沿法线抬高"）：
//   抬高只把起点移出**表面**（沿 N 走 d·1e-3 ≈ 亚像素），但柱子是**从前表面朝远处**挤的，
//   起点只比 z 浅 0.1%·d；射线在**起点所在格**内走不了几像素就会穿回 [z, z+T]，
//   于是立刻命中自己（掠射时尤其必现）。
//   本接口按「DDA 从**起点格的出格点**开始，起点格永不参与判定」设计。
//   这条要补进设计文档 §5.3 —— 等你确认，我再改文档（现在不改，避免把未定的结论写进定稿）。

#ifndef JPOV_SRC_SSR_SSR_RENDERER_H_
#define JPOV_SRC_SSR_SSR_RENDERER_H_

#include <cstdint>

#include "tools/jpov/src/shader_manager.h"

namespace jpov {

// ==================== 输入 ====================
//
// 全部只读。所有字段的初值都是 0/0.0/false，**0 一律表示「未设置」**：Render 直接 LOG(FATAL)，
// 不做任何"猜一个合理值"的兜底（漏设参数应该立刻炸，而不是悄悄换个观感）。
// 例外只有两个：debug_reason（false = 关闭）与 tile_size（= 2，并发粒度，不影响画面）。
struct SsrInputs {
    // ---- 纹理（尺寸都必须等于 width×height，Render 会校验）----

    // 反射源：不透明 3D 已画完的 HDR 颜色（RGBA16F）。
    // **必须**是"半透明/粒子/雾/Bloom 之前、且未加雾"的那一份（见文件头"管线位置"）。
    unsigned int color_tex = 0;

    // 场景深度：MRT#1 的 gl_FragCoord.z（R32F，∈[0,1]，1.0 = 远平面/背景）。
    // 必须是**与 color_tex 同一次光栅化**写出的那张，逐像素 1:1 对齐。
    unsigned int depth_tex = 0;

    // 视空间法线（RGBA 浮点：RG16F/RG32F/RGBA16F 都行，多余分量忽略）。
    //   · .xy = 法线；z 由 sqrt(1 − x² − y²) 重建，取 z ≥ 0（**朝相机**）。
    //     为什么不用深度求导：水面要的是**波浪扰动后**的法线，深度求导只能得到几何面的法线。
    //   · **.z ≥ 0.5 = "这一格有法线数据"**（2026-10-30 加的朝向判据用）。
    //     < 0.5（天空 / 没有几何）时不判命中面朝向，维持旧行为。
    //     ⚙️ 注意：**不是按分辨率直传的属性纹理**，而是接入层降采样后的那份；接入层必须把
    //     .z 一起带下去（ssr_integration.cc 的降采样 FS），否则本判据在遮挡物上静默失效。
    //   · .a 在本模块内**不读**（反射体 mask 由 composite 在全分辨率上处理）。
    //   · 非反射体像素的法线**有意义且必须写**：命中面朝向判据要的就是遮挡物的法线。
    unsigned int normal_tex = 0;

    // ---- 分辨率（§2.1 契约 1：输入什么分辨率，输出什么分辨率）----
    int width = 0;   // > 0
    int height = 0;  // > 0

    // ---- 相机（针孔投影；本模块**不需要任何矩阵**：全部运算在视空间/屏幕空间）----
    // 视空间约定：x 右、y 上、相机看向 −z；视距 d = −z_view > 0（米）。
    float near_plane = 0.0f;      // > 0
    float far_plane = 0.0f;       // > near_plane
    float tan_half_fov_y = 0.0f;  // > 0，垂直半视角的正切（= tan(fov_y / 2)）
    float aspect = 0.0f;          // > 0，屏幕宽 / 高

    // ---- 厚度模型（§9，唯一允许的假设）----

    // 允许的「拉黏」像素数 N_px：倒影比真实物体粗多少像素。建议 10（§9.3 的默认档）。
    //   **接口这里收 N_px 而不是最终系数 c**：c = N_px·θ_px 依赖 FOV 与屏幕高，
    //   由模块自己算（θ_px 需要 height，模块本来就知道），调用方少一个必须换算的派生量，
    //   也就少一次"写死 0.010 然后在别的分辨率上翻车"。
    //   （这是相对设计文档 §2 的 `thickness_coefficient` 的一处**故意偏离**，理由见 §9.3
    //     "不要写死一个绝对系数"；若你更想要原样传 c，改回来只是一个乘法。）
    float thickness_pixels = 0.0f;  // > 0

    // 米，T 的数值下限。正常相机下恒不生效（T = c·d ≥ c·near > 0）——
    // 它的唯一职责是让"T 永远 > 0"这条不变量**不依赖**相机参数（near → 0 的退化相机）。
    // 建议 1e-4。不是物理量，不要拿它调观感。
    float min_thickness_m = 0.0f;  // > 0

    // ---- 行进 ----
    // 射线长度上限（米）。建议 = far_plane；超过 far 的部分没有任何深度数据，
    // 内部再与 far_plane 取 min（此处传大一点不会出错，只是无效）。
    float max_distance_m = 0.0f;  // > 0
    // 屏幕空间射线长度上限（**像素**）：覆盖率与成本是同一个数。
    //   覆盖 = min(max_ray_pixels, 屏幕对角线)（精确 —— 裁剪后不可能更长）；
    //   成本 ≤ 1.414·该值 + T² 次判据。
    // 填超过对角线**不会更慢也不会出错**（段尾被 ray.exit 截住，循环次数自限），
    // 只是没有额外收益；模块对此**不告警**（见 Render 里的说明）。
    // 它与分辨率的关系：单位是**像素**，所以高分辨率下同一个数值看到的世界距离更近。
    //   要观感一致就由调用方按 `fraction × 屏幕高` 给（与 §9.3 用 θ_px 折算厚度同一套
    //   逻辑，模块不替你缩放）。建议 0.15~0.35 × 屏幕高度。
    int max_ray_pixels = 0;  // > 0

    // 每镜面像素切几条 lane：tile 边长 T ∈ {1,2,4,8}，K = T² ∈ {1,4,16,64}。
    //   · T 必须**偶数且为 2 的幂**（T=1 除外）：否则一个 2×2 quad 会跨 tile，
    //     隐式 LOD / fwidth 立刻出错。T=8 的 tile 恰是 16 个完整 quad，安全。
    //   · T 只决定"同一笔预算切成几份并发跑"：**不改变覆盖、不改变 radiance，只改耗时**
    //     （调试用的 hit_s 是格内中点，会随段边界挪动，但一定落在同一格）。
    //     代价是 slice 缓冲 (W·T)×(H·T) R32F ⇒ T² 倍显存 + T² 倍 fragment 数。
    //   · 组合规则：段长 L = max_ray_pixels / T²，建议 L ≥ 4 px（冗余 ≈ 1 + 1/L）。
    //     **快速口诀：T² ≤ max_ray_pixels / 4（单位 px）**
    //       T=1 任意 · T=2 需 ≥16 · T=4 需 ≥64 · T=8 需 ≥256
    //     例：1/8 分辨率 + T=8 + max_ray_pixels=40 ⇒ L=0.625 px、判据次数 ×2.67；
    //     同参数 T=2 ⇒ L=10 px、冗余 1.1×。
    //   · **这不是错误，也不告警**：JPOV 不负责"保证用户不做出浪费的配置"。搭配规则只在
    //     这段注释里给出（要查的人会来查）。真正的 FATAL 只留给会炸的：忘设参数、
    //     非法枚举、超纹理尺寸 / 超显存。
    //   · 默认 2：正好一个 quad 服务一个镜面像素（SIMD 粒度天然对齐），显存 4×。
    int tile_size = 2;

    // 仅测试/调试：true 时额外写 reason_tex（见 SsrResult）。**不参与计算**，
    // 关掉时对 radiance_tex 零影响（gold 用 radiance，三态用它，§11.2-5）。
    bool debug_reason = false;
};

// ==================== 输出 ====================
//
// 模块内部分配、懒创建、尺寸变化时重建（§2）。生命周期归 SsrRenderer 所有，
// 调用方只借用；不要在 Render 之外保存又跨帧使用（尺寸一变就换了对象）。
struct SsrOutputs {
    // RGBA16F，与输入同分辨率、逐像素 1:1（不可重采样）。
    //   rgb = 镜面方向命中那一格的颜色（HDR、未加雾、未 tonemap、**纯辐亮度**）
    //   a   = A ∈ {0,1}：1 = "这个答案来自屏幕数据"；0 = "拿不到"（§6）
    unsigned int radiance_tex = 0;

    // R8UI（仅 debug_reason == true 时非 0）：每像素写一个 SsrResult 的数值。
    // 供 §11.2-5 的"A 三态"测试断言分类，不进任何生产路径。
    unsigned int reason_tex = 0;

    // R32F（仅 debug_reason == true 时非 0）：每像素写整条射线的碰撞位置 s（像素弧长，
    // 无命中写哨兵 +1e30）。§11.2-3 的"命中格与解析解一致"最自然的断言对象就是它
    // （靠颜色反推很脆）；它同时是 tile 等价性测试的直接证据：s 相同 ⇒ 命中格相同。
    unsigned int hit_s_tex = 0;
};

// 像素级结算结果。**只用于调试/测试**（写进 reason_tex），不参与渲染（§5.4）。
enum class SsrResult : std::uint8_t {
    // 某格的区间重叠 ⇒ rgb = 该格颜色, A = 1
    kHit = 0,
    // 全程留在屏内、没碰到任何柱子 ⇒ A = 0。**交给 composite 的环境镜面项**：
    // 模块不持有天空探针，而 EnvSpecularTerm 对"真的什么都没有"恰好是正确值（§5.4 ★）。
    kSky = 1,
    // 射线出屏 / 出视锥 / 起点贴边 ⇒ A = 0（显式：没有数据，不是"没有东西"）
    kOffscreen = 2,
    // 可用射线长度 ≈ 0（起点已在 far 平面）或超出 max_ray_pixels 预算 ⇒ A = 0
    // （超预算算"不知道"而不是"没命中"：覆盖率掉、正确性不掉）
    kTooShort = 3,
};

// ==================== 渲染器 ====================
//
// 生命周期（与 SmaaRenderer / VolumeFireRenderer 同款）：
//     Init(shader_mgr) → 每帧 Render(inputs) → Finalize()（析构也会调）
// 不启用 SSR 时（Renderer 侧没有调用它）本类完全不被触碰：零开销、零回归。
//
// GL 侧约定：
//   · Render 自己绑 FBO / 设 viewport，返回前**完整恢复调用前的状态**：FBO、viewport、
//     program、unit 0..3 的纹理绑定、混合/深度/剔除开关。调用方不需要自己收拾。
//   · 本模块是 post-process pass，纹理单元**从 0 起自己绑**，不进 texture_units.h 的
//     跨 pass 分配表（那张表管的是"同时活跃"的 3D 主链路资源，见其文件头）。
class SsrRenderer {
public:
    // slice 缓冲的字节上限（(W·T)(H·T) 个 R32F）。超了直接 FATAL 并把算出来的数字打出来，
    // 让用户看到"是 tile 太大还是分辨率太高"，而不是事后对着 "framebuffer incomplete" 猜。
    // 纹理边长上限**不写死常量**：Init 时查 GL_MAX_TEXTURE_SIZE（那是驱动属性，不是我们的选择）。
    static constexpr long long kMaxSliceBytes = 512LL << 20;

    SsrRenderer();
    ~SsrRenderer();

    SsrRenderer(const SsrRenderer&) = delete;
    SsrRenderer& operator=(const SsrRenderer&) = delete;

    // 编译两趟 program（march / resolve），tile 变体用 ShaderSource::defines 区分。
    // Pre-condition: GL context 已激活（Renderer::Init 内调用）。
    // 可重复调用（先内部 Finalize 再重建）。
    void Init(ShaderManager* shader_mgr);

    // 释放所有 GL 对象（program/FBO/纹理）。幂等；析构会调用。
    void Finalize();

    // 跑一遍 SSR，返回本次输出（模块自持，别跨帧缓存）。
    //
    // Pre-condition（任一不满足 ⇒ LOG(FATAL)，不静默退化）：
    //   · 已 Init；三张输入纹理都 ≠ 0，且实际尺寸 == width×height；
    //   · 0 < width,height；near_plane > 0；far_plane > near_plane；tan_half_fov_y > 0；
    //     aspect > 0；thickness_pixels > 0；min_thickness_m > 0；max_ray_pixels > 0；
    //   · tile_size ∈ {1,2,4,8}；
    //   · width·tile、height·tile 都不超 GL_MAX_TEXTURE_SIZE（Init 时查一次），
    //     且 (W·T)(H·T)·4B ≤ kMaxSliceBytes；
    //   · color/depth/normal 都不是本模块自己的 radiance_tex / hit_s_tex
    //     （契约 6：不许形成反馈环）。
    //   · 段长 L = max_ray_pixels / T² < 4 px 只是慢（判据次数 ×(1+1/L)）：不失败、
    //     **也不告警** —— 画面完全相同，不该占日志。
    const SsrOutputs& Render(const SsrInputs& in);

private:
    // slice 目标与输出目标（radiance [+ reason / hit_s]）。尺寸 / tile / debug 变化时重建。
    // **Render 内零分配**：热路径上只有 viewport / 绑定 / draw。
    void EnsureTargets(int w, int h, int tile, bool debug);
    void DestroyTargets();

    ShaderManager* shader_mgr_ = nullptr;

    // program 按 tile 取变体（T 是编译期常量，用 ShaderSource::defines 出 TILE=1/2/4/8；
    // ShaderManager 按名字缓存，tag 里带 T）。C++ 侧只有一条代码路径。
    unsigned int prog_march_ = 0;        // 全屏 VS + 单段 march FS（画 (W·T)×(H·T)）
    unsigned int prog_resolve_ = 0;      // 全屏 VS + T² 取 min / 取色 FS（画 W×H）
    unsigned int prog_resolve_debug_ = 0;  // 同上 + SSR_DEBUG（多写 reason / hit_s 两个附件）

    unsigned int slice_fbo_ = 0;      // march 的目标（挂 slice_tex_）
    unsigned int slice_tex_ = 0;      // R32F，(W·T)×(H·T)；每 texel = 一个 lane 的 s_mid
    unsigned int fbo_ = 0;            // resolve 的目标（挂 radiance [+ reason / hit_s]）

    SsrOutputs outputs_;
    int width_ = 0;
    int height_ = 0;
    int tile_ = 0;                              // 当前 slice / 输出目标对应的 tile 边长
    bool debug_ = false;                        // 当前输出目标是否带调试附件
    int max_texture_size_ = 0;                  // Init 时查的 GL_MAX_TEXTURE_SIZE
    bool initialized_ = false;
};

// ==================== 实现时的算法骨架（按这个顺序写 FS，别跳步）====================
//
// ① 反构射线（全部在视空间，不用矩阵）
//      n       = 2·(gl_FragCoord.xy / vec2(W,H)) − 1                  // 真 NDC.xy ∈ (−1,1)
//      dir     = vec3(n.x·aspect·tan_half_fov_y, n.y·tan_half_fov_y, −1)   // 视空间方向，未归一化
//      ndc.z   = 2·depth − 1
//      d_surf  = 2·near·far / ((far + near) − ndc.z·(far − near))     // 与 ZView() 同一份公式
//      P       = dir · d_surf                                         // 视空间起点（P.z = −d_surf）
//      N       = vec3(normal_tex.xy, sqrt(max(0, 1 − x² − y²)))       // 朝相机
//      R       = reflect(normalize(P), N)                             // 入射方向 = 相机→表面
//    退化守卫：d_surf 的分母趋 0（near≈0 且 ndc.z→1）会得到 NaN，NaN 会顺着后处理
//    污染整帧；用 !(abs(denom) > 1e-6) 拦（同时拦 NaN），退化成 max(near, 1e-4)。
//
// ② 起点卫生 + 射线裁剪
//      P += N · (d_surf · 1e-3)         // 相对量，不是世界常量；与厚度 T 是两件事（§5.3）
//      R.z > 0 ⇒ rayLen = min(max_distance_m, far, (−near − P.z) / R.z)
//      depth == 1.0（清空值 = 远平面，天空/背景，d_surf == far）
//        ⇒ 直接 a = 0、reason = kTooShort，**不发射线**（天空占了半屏的场景最省的是这一步）
//      rayLen ≈ 0 ⇒ 同上（kTooShort）
//    起点格整格跳过之后，这个法线偏移的职责只剩「别擦到相邻格的表面」（掠射），
//    0.1% 是 §5.3 的保守值；若掠射仍脏，先调它，别动 T。
//
// ③ 屏幕参数化（σ = 像素弧长）
//      s0 = 起点像素坐标；s1 = 把 P + R·rayLen 投回屏幕；
//      矩形裁剪到 [0,W]×[0,H]，同时按**同一个**裁剪参数把 (w0, w1) 一起夹紧
//      （w = 1/d 对屏幕位置是仿射的 ⇒ 裁剪后端点上的 w 直接按比例算，精确）
//      之后任何 σ 处：w(σ) = mix(w0, w1, σ / S)，d(σ) = 1 / w(σ)
//
// ③ 屏幕参数化 + 矩形裁剪（σ = 像素弧长）
//      s0 = 起点像素坐标；s1 = 把 P + R·rayLen 投回屏幕；
//      矩形裁剪到 [0,W]×[0,H]，同时按**同一个**裁剪参数把 (w0, w1) 一起夹紧
//      （w = 1/d 对屏幕位置是仿射的 ⇒ 裁剪后端点上的 w 直接按比例算，精确）
//      之后任何 σ 处：w(σ) = mix(w0, w1, σ / S)，d(σ) = 1 / w(σ)
//      **先裁剪再切段**：否则出屏的那些段白跑，还占着 lane。
//
// ④ 切段（lane 的工作分配）
//      L = max_ray_pixels / T²；lane k 覆盖 σ ∈ [k·L, (k+1)·L)；
//      起点像素 = s0 + ê·(k·L)，w(k·L) 用同一份仿射式（精确，不用累加）
//      · lane 起点在屏外、或 k·L ≥ S ⇒ 直接写哨兵 s = +1e30（空转只有一条比较）
//      · **起点格跳过只对 lane 0 有意义**（其余 lane 的起点不在反射体表面上）；
//        lane 0 的 DDA 从起点格的**出格点**开始、起点格永不参与判定，否则射线会在
//        自己的柱子里立刻命中自己（见文件头"待确认"）。
//
// ⑤ 段内 DDA（每格三行判据，§5.1 —— 整个 march 的核心）
//      (w_in, w_out) ← 射线在本格内的 σ 区间端点（段内 w 单调 ⇒ 端点即极值）
//      d_lo = 1 / max(w_in, w_out);  d_hi = 1 / min(w_in, w_out)
//      z, T ← 本格深度与厚度（T = max(c·z, min_thickness_m)，用**本格**的 z）
//      if (d_hi < z)      continue;      // 整段在柱子前方（水面最常见）
//      if (d_lo > z + T)  continue;      // 整段在柱子后方（穿过去了）
//      if (R·N ≥ 0)       continue;      // 背面命中（2026-10-30 第一档，见下）
//      hit ⇒ s_mid = ½(s_enter + s_exit)   // **命中格内**的中点，写 slice_tex_ 后 return
//      步数上限 = ceil(1.414·L) + 3（对角线最坏情况）⇒ 满段永远走得完、绝不半路截断；
//      提前返回只发生在命中时。
//
//    等价写法（省掉每格除法，实现时可用）：判据整体搬到 w 空间 ——
//      [w_lo, w_hi] ∩ [1/(z+T), 1/z] ≠ ∅，且 T = c·z ⇒ 下界 = w/(1+c)。
//    注意：min_thickness_m 生效时这个化简不成立，需回退到 d 空间那三行。
//
// ⑥ resolve（1:1 一趟，取 min 与取色合在一起）
//      s = min(T² 个 texelFetch)                  // T 行 × 每行 T 个连续纹素，L1 友好
//      s ≥ 哨兵 ⇒ a = 0；kSky / kOffscreen 由"是否曾出屏"区分，写进 reason
//      否则 pos = s0 + ê·s ⇒ uv = floor(pos) ⇒ texelFetch(color) ⇒ 写 (color, a = 1)
//      ⚠️ 这一趟**本来就要存在**（s → 命中格 → 颜色），min 塞进来 pass 数 +0；边际成本
//         是 T² 次取样，而 march 本身要 ~1.4·max_ray_pixels 次 ⇒ 4%(T=4) / 18%(T=8)。
//
//      ★ 为什么**不**做多级 2×2 金字塔（2026-10-29 算过，别再算一遍）：
//        T=8 时「一趟 64 fetch」vs「8×8→4×4→2×2→1×1 三级」：
//          方案        fetch指令  写纹素  fragment数  128B行(读写)  pass
//          一趟 64          64       1        1          8 + 1        1
//          三级金字塔       12       3       21         14 + 7        3
//        64 次 fetch 是 8 行 × 每行 32B 连续（L1 命中），真实只有 8 条缓存行；金字塔每级
//        都要把上一级的**新缓冲**再读回来（已出 cache）⇒ 行数反而更多，且 fragment 数是
//        21 倍、pass 数 3 倍。两者的输出**逐字节相同**（min 精确且可结合），纯性能取舍。
//        只有两种情况值得重访：T ≥ 16（256 纹素），或升到 GLSL 4.x 用 textureGather
//        （一次取 2×2，T=8 从 64 次变 16 次 fetch，仍是一趟）。
//
// ⑦ 调试（不额外开 pass，全部顺手写在 ⑥ 里）
//      reason_tex ← SsrResult；hit_s_tex ← s
//
// ── 数值卫生（写代码时逐条问自己）─────────────────────────────────────────
//  · **永远**不要在 d 空间做插值，只在 w = 1/d 空间插值（§3.1）。
//  · 栅格化像素中心是 gl_FragCoord.xy（已是 x+0.5），不要自己再加 0.5。
//  · N 重建完**归一化一次**：xy 长度因数值误差 > 1 时 z 会取 0，不归一的话 |N| > 1，
//    reflect 会把 R 一起拉长（法线贴图/波浪扰动很容易越界，这是真会踩的坑）。
//  · texelFetch 的坐标是**整数格**：格 (i,j) 用 texelFetch(tex, ivec2(i,j), 0)。
//    GLSL 330 没有 textureGather（那是 4.00），2×2 下采样用 4 次 texelFetch。
//  · 浮点行号/列号不能用来选纹理行（llvmpipe 上 float(id)/N 会略大于整数 ⇒ 双线性
//    混到相邻行）。本模块只用整数坐标取格，天然规避。
//  · **镜面像素的 uv 必须用 tile 中心**：uv = (floor(gl_FragCoord.xy / T) + 0.5) / (W,H)；
//    写成 gl_FragCoord.xy / (T·W) 会把采样点整体偏 (T−1)/(2T) px ⇒ 倒影平移 + 边缘一圈
//    脏边，而且症状看着完全像别的问题。
//  · tile 边长 T **必须是偶数且为 2 的幂**：2×2 quad 若跨 tile，同一 quad 的 4 个 lane
//    会属于两个镜面像素 ⇒ 隐式 LOD / fwidth 立刻出错（本模块不用导数，但 T=3/6 这类值
//    一律禁掉，别给将来留坑）。
//  · 哨兵用 +1e30 而不是 inf：inf 参与 min 是合法的，但写进 R32F 再读回来时某些驱动
//    会把 inf 规整掉；1e30 在 R32F 里可精确表示，且远大于任何合理 s。

}  // namespace jpov

#endif  // JPOV_SRC_SSR_SSR_RENDERER_H_
