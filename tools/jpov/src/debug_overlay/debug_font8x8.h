// 一个字体都没注册的 app（`kDefaultFonts` 恒为空）。把 DejaVu 之类的 TTF 塞进
// .h 要 ~700KB 且要新增「从内存加载 TTF」的路径；而调试文本只需要 ASCII，
// 一张 95×8 字节的点阵表就够了（零外部依赖、零文件、零分配）。
//
