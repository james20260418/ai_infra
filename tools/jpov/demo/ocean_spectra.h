// 把预设铺成一份可渲染的 WaterWaves。三个倍率是面板滑条：
//   amp_scale    = 主波振幅倍率（不改波长/方向 ⇒ 不改形态）
//   detail_scale = 细节短波振幅倍率
//   warp_amp_m   = **覆盖值**（<0 ⇒ 用预设自带值）
inline jpov::WaterWaves MakeOceanWaves(int index, float amp_scale, float detail_scale,
                                       float warp_amp_m) {
    const OceanSpectrumPreset& p = OceanPreset(index);
    jpov::WaterWaves w;
    w.enabled = true;
    w.num_waves = std::min(p.num_waves, jpov::WaterWaves::kMaxWaves);
    for (int i = 0; i < w.num_waves; ++i) {
        w.waves[i] = p.waves[i];
        w.waves[i].amplitude_m *= amp_scale;
    }
    w.num_detail_waves = std::min(p.num_detail, jpov::WaterWaves::kMaxDetailWaves);
    for (int i = 0; i < w.num_detail_waves; ++i) {
        w.detail_waves[i] = p.details[i];
        w.detail_waves[i].amplitude_m *= detail_scale;
    }
    w.warp_amplitude_m = (warp_amp_m >= 0.0f) ? warp_amp_m : p.warp_amp_m;
    for (int j = 0; j < jpov::WaterWaves::kWarpCarriers; ++j) {
        w.warp_wavelength_m[j] = p.warp_lam_m[j];
        w.warp_dir_x[j] = p.warp_dir_x[j];
        w.warp_dir_z[j] = p.warp_dir_z[j];
        w.warp_phase_rad[j] = 0.9f * (j + 1);   // 错开相位，避免四条同相叠成单载波
    }
    w.stokes_second_order = true;
    w.speed_scale = 1.0f;
    w.fade_start_m = 300.0f;
    w.fade_end_m = 2000.0f;
    w.flow_align = 0.6f;
    w.flow_wind_gain = 0.6f;
    w.flow_uv_scale = 1.0f / 220.0f;
    return w;
}

