// JPOV 屏幕空间反射（SSR）接口层配置 —— GL-free，render_command 与 src/ssr 共用
//
// 一句话：把「不透明 3D 已经画好的画面」当成 2.5D 场景（颜色 + 深度），
// 在屏幕空间里逐像素发射反射射线，把撞到的东西当成倒影叠回画面。
//
// 为什么是「后处理」而不是「材质里算」：
//   SSR 需要**本帧已经画好的颜色与深度**，而材质着色时这些还不存在。
//   所以它天然只能是一个独立 pass（与粒子 / 体积火 / 条带 / 雾平级），
//   在**不透明 3D 之后、半透明与雾之前**执行。
//
// 与「环境镜面（EnvSpecular）」的分工：
//   * EnvSpecular（PR #228）：天光 cubemap 的镜面反射 —— 便宜、无遮挡概念、到处都能用；
//   * SSR（本模块）：**场景内几何**的倒影 —— 贵、只能在屏幕内、但它是真倒影。
//   两者是同一物理量的两种估计。**本版它们是叠加关系（不互相替换）**：同时开会偏亮，
//   验收时二选一（见 demo 的 SSR 开关会同时把 env 关掉，避免双计）。
//   想做成「命中就用 SSR、没命中就回退探针」需要材质侧参与（前向管线里 SSR 一定晚于
//   材质着色，同帧无法回灌）——留给后续，见 docs/jpov_ssr_design.md §7。
//
// 设计要求（Danis 2026-10-26）：**一个总开关控制**、参数暴露出来做 A/B、
//   Hi-Z 实现、只服务「3D 实心部分」。

#ifndef JPOV_INTERFACE_SSR_TYPES_H_
#define JPOV_INTERFACE_SSR_TYPES_H_

namespace jpov {

// 单条反射射线在屏幕空间里的行进参数（都是「观感/性能」旋钮，不是物理量）。
struct SsrConfig {
    // 总开关。false（默认）= 整个 pass 不跑，零开销零回归。
    bool enabled = false;

    // 反射缓冲相对 3D FBO 的分辨率倍率（must be in (0, 1]）。
    // 水面/金属的倒影本来就被法线打碎，1/2 通常看不出来；1/4 更省。
    // 成本 ∝ 倍率²（像素数）。
    float resolution_scale = 0.5f;

    // Hi-Z 起始层：0 = **关闭 Hi-Z**（全分辨率逐像素细步进，最准最慢）；
    //   1~4 = 从 2^level 像素的格子开始粗走，撞到可能命中的格子就下探一层（推荐 2）。
    // 层数越高越省步数，但粗层漏检（细长物体被整格跳过）的风险越大。
    int hiz_start_level = 2;

    // 每条射线的最大步进次数（含粗层步与下探步）。命中质量与成本的主旋钮。
    int max_steps = 32;

    // 命中后二分细化的次数（把命中位置收敛到亚像素）。0 = 直接用粗命中点（会抖）。
    int refine_steps = 4;

    // 「薄片容忍厚度」（视图空间米）。光线穿到表面背后不足这个厚度才算真命中；
    // 超过则认为是穿过了薄物体（树叶/栏杆）继续走。太大 = 远处物体被误当命中，
    // 太小 = 薄片漏光。（我们的场景树叶多，这个值比一般引擎要放宽些。）
    float thickness_m = 0.6f;

    // 射线最远行进距离（米）。远于此直接放弃并回退天空。
    float max_distance_m = 80.0f;

    // 粗糙度上限：**超过这个粗糙度的像素不做 SSR**（改用天空兜底 / 交给 env 探针）。
    // 物理上粗糙表面的反射是一片模糊，单条射线代表不了，硬做只会得到"脏"的倒影。
    float roughness_cutoff = 0.4f;

    // 屏幕边缘淡出：命中点靠屏幕边界时降低权重（那里本来就没有可信数据，
    // 不淡出会看到反射在画面边缘"被切断"）。
    bool fade_screen_edges = true;
};

}  // namespace jpov

#endif  // JPOV_INTERFACE_SSR_TYPES_H_
